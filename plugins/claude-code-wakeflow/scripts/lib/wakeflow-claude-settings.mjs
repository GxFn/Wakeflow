function statuslineSpawn({ workspaceRoot, source, stdin, cwd }) {
  const encodedRoot = Buffer.from(workspaceRoot, "utf8").toString("base64url");
  const runtimeArgs = [STATUSLINE_MARKER, ROOT_ARGUMENT, encodedRoot];
  if (source === "template") {
    const code = STATUSLINE_ASSET.replace(/^#![^\n]*\n/u, "");
    return spawnSync(process.execPath, [
      "--input-type=module",
      "--eval",
      code,
      "--",
      ...runtimeArgs,
    ], {
      cwd,
      encoding: "utf8",
      input: stdin,
      timeout: 5_000,
      maxBuffer: MAX_STATUSLINE_OUTPUT_BYTES,
      shell: false,
    });
  }
  const assetFile = path.resolve(workspaceRoot, ...STATUSLINE_ASSET_REF.split("/"));
  const current = readStableFile(workspaceRoot, STATUSLINE_ASSET_REF, {
    maximumBytes: MAX_ASSET_BYTES,
    label: "Claude statusline asset",
  });
  if (current.state !== "file" || current.bytes !== STATUSLINE_ASSET || current.mode !== "0600") {
    fail("wakeflow-claude-settings-asset-runtime", "installed statusline asset is not exact current bytes and mode");
  }
  return spawnSync(process.execPath, ["--", assetFile, ...runtimeArgs], {
    cwd,
    encoding: "utf8",
    input: stdin,
    timeout: 5_000,
    maxBuffer: MAX_STATUSLINE_OUTPUT_BYTES,
    shell: false,
  });
}

