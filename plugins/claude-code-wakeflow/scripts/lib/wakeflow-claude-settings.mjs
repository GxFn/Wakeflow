function assertMaintenanceContext(workspaceRoot, context) {
  if (context === null || typeof context !== "object") {
    fail("wakeflow-claude-settings-mutation", "Claude settings maintenance requires a branded context");
  }
  // 先验证 WeakMap 品牌，再读取 recoveryGeneration；伪造context getter不得在准入前执行。
  try {
    assertWakeflowMutationContext({ workspaceRoot, context });
  } catch (cause) {
    fail("wakeflow-claude-settings-mutation", "Claude settings maintenance context is invalid", {}, cause);
  }
  const mode = context.recoveryGeneration > 0 ? "recovery-cleanup" : "maintenance";
  try {
    assertWakeflowMutationContext({ workspaceRoot, context, mode });
  } catch (cause) {
    fail("wakeflow-claude-settings-mutation", "Claude settings maintenance context is invalid", {}, cause);
  }
}

function operationMaximumBytes(operation) {
  return operation.component === "statusline-asset" ? MAX_ASSET_BYTES : MAX_SETTINGS_BYTES;
}

function publicFileNode(source) {
  if (source.state === "absent") return { type: "absent" };
  if (source.state !== "file") return null;
  return { type: "file", mode: source.mode, digest: source.sha256 };
}

function sameFileIdentity(source, expected) {
  return source.state === "file"
    && expected.state === "file"
    && same(source.sourceIdentity, expected.sourceIdentity)
    && source.sha256 === expected.sha256
    && source.mode === expected.mode;
}

function inspectMaintenanceFileState(root, privateOperation, publicOperation, step) {
  const final = readStableFile(root.absolute, privateOperation.ref, {
    maximumBytes: operationMaximumBytes(privateOperation),
    label: `${privateOperation.component} maintenance final`,
    allowedLinkCounts: [1, 2],
  });
  const stage = readStableFile(root.absolute, publicOperation.stageRef, {
    maximumBytes: operationMaximumBytes(privateOperation),
    label: `${privateOperation.component} maintenance stage`,
    allowedLinkCounts: [1, 2],
  });
  if ([final.state, stage.state].includes("unsafe")) {
    fail("wakeflow-claude-settings-maintenance-residue", "Claude settings maintenance observed unsafe residue");
  }
  const sourceExact = privateOperation.source.state === "absent"
    ? final.state === "absent"
    : sameFileIdentity(final, privateOperation.source);
  const finalTarget = final.state === "file"
    && final.sha256 === privateOperation.desired.digest
    && final.mode === privateOperation.desired.mode;
  const stageAbsent = stage.state === "absent";
  const stageTarget = stage.state === "file"
    && stage.sha256 === privateOperation.desired.digest
    && stage.mode === privateOperation.desired.mode;
  const linkedPair = finalTarget
    && stageTarget
    && final.sourceIdentity.deviceId === stage.sourceIdentity.deviceId
    && final.sourceIdentity.inodeId === stage.sourceIdentity.inodeId
    && final.sourceIdentity.linkCount === "2"
    && stage.sourceIdentity.linkCount === "2";
  let state = "illegal";
  if (sourceExact && stageAbsent) state = "initial";
  else if (sourceExact && stageTarget && stage.sourceIdentity.linkCount === "1") state = "prepared";
  else if (finalTarget && stageAbsent) state = "committed";
  else if (privateOperation.source.state === "absent" && linkedPair) state = "committed-pair";
  const observation = state === "initial"
    ? {
        source: { ref: step.source.ref, ...publicOperation.source },
        staging: { ref: step.staging.ref, type: "absent" },
        final: { ref: step.final.ref, ...publicOperation.source },
      }
    : state === "prepared"
      ? {
          source: { ref: step.source.ref, ...publicOperation.source },
          staging: { ref: step.staging.ref, ...publicOperation.target },
          final: { ref: step.final.ref, ...publicOperation.source },
        }
      : new Set(["committed", "committed-pair"]).has(state)
        ? {
            source: { ref: step.source.ref, ...publicOperation.target },
            staging: { ref: step.staging.ref, type: "absent" },
            final: { ref: step.final.ref, ...publicOperation.target },
          }
        : null;
  return { state, observation, final, stage };
}

function openSafeDirectory(directory, expectedIdentity = null) {
  let descriptor = null;
  try {
    descriptor = fs.openSync(
      directory,
      fs.constants.O_RDONLY | (fs.constants.O_DIRECTORY ?? 0) | (fs.constants.O_NOFOLLOW ?? 0),
    );
    const stat = fs.fstatSync(descriptor, { bigint: true });
    const current = fs.lstatSync(directory, { bigint: true });
    const euid = typeof process.geteuid === "function" ? BigInt(process.geteuid()) : null;
    if (
      !stat.isDirectory()
      || stat.isSymbolicLink()
      || euid === null
      || stat.uid !== euid
      || !sameStat(stat, current)
      || (expectedIdentity && !same(statSourceIdentity(stat), expectedIdentity))
    ) fail("wakeflow-claude-settings-maintenance-root", "maintenance directory is unsafe or stale");
    return { descriptor, stat, identity: statSourceIdentity(stat) };
  } catch (cause) {
    if (descriptor !== null) fs.closeSync(descriptor);
    if (cause instanceof WakeflowClaudeSettingsError) throw cause;
    fail("wakeflow-claude-settings-maintenance-root", "maintenance directory cannot be opened", {}, cause);
  }
}

function fileStepHandler(workspaceRoot, privateOperation, publicOperation, root, step) {
  let lastPrepared = null;
  const parent = path.dirname(path.resolve(root.absolute, ...privateOperation.ref.split("/")));
  const matchesPrepared = (inspected, expected) => (
    inspected.state === "prepared"
    && same(inspected.stage.sourceIdentity, expected.stageIdentity)
    && (
      privateOperation.source.state !== "file"
      || same(inspected.final.sourceIdentity, expected.sourceIdentity)
    )
  );
  return Object.freeze({
    prepare(args) {
      const { context } = callbackArguments(args, ["context"], "Claude settings prepare arguments");
      assertMaintenanceContext(workspaceRoot, context);
      const inspected = inspectMaintenanceFileState(root, privateOperation, publicOperation, step);
      if (inspected.state !== "initial") {
        fail("wakeflow-claude-settings-plan-stale", "Claude settings source changed before prepare");
      }
      const parentHandle = openSafeDirectory(parent);
      let descriptor = null;
      try {
        if (inspectMaintenanceFileState(root, privateOperation, publicOperation, step).state !== "initial") {
          fail("wakeflow-claude-settings-plan-stale", "Claude settings source changed after parent admission");
        }
        descriptor = fs.openSync(
          path.resolve(root.absolute, ...publicOperation.stageRef.split("/")),
          fs.constants.O_WRONLY
            | fs.constants.O_CREAT
            | fs.constants.O_EXCL
            | (fs.constants.O_NOFOLLOW ?? 0),
          0o600,
        );
        fs.writeFileSync(descriptor, privateOperation.desired.content);
        fs.fchmodSync(descriptor, Number.parseInt(privateOperation.desired.mode, 8));
        fs.fsyncSync(descriptor);
        fs.fsyncSync(parentHandle.descriptor);
      } catch (cause) {
        if (cause instanceof WakeflowClaudeSettingsError) throw cause;
        fail("wakeflow-claude-settings-maintenance-prepare", "Claude settings stage publication failed", {}, cause);
      } finally {
        if (descriptor !== null) fs.closeSync(descriptor);
        fs.closeSync(parentHandle.descriptor);
      }
      if (inspectMaintenanceFileState(root, privateOperation, publicOperation, step).state !== "prepared") {
        fail("wakeflow-claude-settings-maintenance-prepare", "Claude settings stage is not exact");
      }
    },

    observe(args) {
      const { context } = callbackArguments(args, ["context"], "Claude settings observe arguments");
      assertMaintenanceContext(workspaceRoot, context);
      const inspected = inspectMaintenanceFileState(root, privateOperation, publicOperation, step);
      if (inspected.state === "illegal" || inspected.observation === null) {
        fail("wakeflow-claude-settings-maintenance-residue", "Claude settings file state is illegal");
      }
      const parentHandle = openSafeDirectory(parent);
      const parentIdentity = parentHandle.identity;
      fs.closeSync(parentHandle.descriptor);
      lastPrepared = inspected.state === "prepared" ? {
        sourceIdentity: inspected.final.state === "file" ? inspected.final.sourceIdentity : null,
        stageIdentity: inspected.stage.sourceIdentity,
        parentIdentity,
      } : null;
      return inspected.observation;
    },

    commit(args) {
      const { context } = callbackArguments(args, ["context"], "Claude settings commit arguments");
      assertMaintenanceContext(workspaceRoot, context);
      if (!lastPrepared) fail("wakeflow-claude-settings-maintenance-race", "commit lacks prepared observation");
      const expected = lastPrepared;
      lastPrepared = null;
      const inspected = inspectMaintenanceFileState(root, privateOperation, publicOperation, step);
      if (!matchesPrepared(inspected, expected)) {
        fail("wakeflow-claude-settings-plan-stale", "Claude settings source changed before commit");
      }
      const parentHandle = openSafeDirectory(parent, expected.parentIdentity);
      try {
        if (!matchesPrepared(
          inspectMaintenanceFileState(root, privateOperation, publicOperation, step),
          expected,
        )) fail("wakeflow-claude-settings-plan-stale", "Claude settings source changed after parent admission");
        const stage = path.resolve(root.absolute, ...publicOperation.stageRef.split("/"));
        const final = path.resolve(root.absolute, ...privateOperation.ref.split("/"));
        if (privateOperation.source.state === "absent") fs.linkSync(stage, final);
        else fs.renameSync(stage, final);
        fs.fsyncSync(parentHandle.descriptor);
      } catch (cause) {
        if (cause instanceof WakeflowClaudeSettingsError) throw cause;
        fail("wakeflow-claude-settings-maintenance-commit", "Claude settings commit failed", {}, cause);
      } finally {
        fs.closeSync(parentHandle.descriptor);
      }
      const committed = inspectMaintenanceFileState(root, privateOperation, publicOperation, step);
      const expectedState = privateOperation.source.state === "absent" ? "committed-pair" : "committed";
      if (committed.state !== expectedState) {
        fail("wakeflow-claude-settings-maintenance-commit", "Claude settings commit is not exact");
      }
    },

    cleanup(args) {
      const { context } = callbackArguments(args, ["context"], "Claude settings cleanup arguments");
      assertMaintenanceContext(workspaceRoot, context);
      const inspected = inspectMaintenanceFileState(root, privateOperation, publicOperation, step);
      if (inspected.state === "committed") return;
      if (inspected.state !== "committed-pair") {
        fail("wakeflow-claude-settings-maintenance-cleanup", "cleanup lacks committed pair");
      }
      const parentHandle = openSafeDirectory(parent);
      try {
        const current = inspectMaintenanceFileState(root, privateOperation, publicOperation, step);
        if (
          current.state !== "committed-pair"
          || !same(current.final.sourceIdentity, inspected.final.sourceIdentity)
          || !same(current.stage.sourceIdentity, inspected.stage.sourceIdentity)
        ) fail("wakeflow-claude-settings-maintenance-race", "committed pair changed after parent admission");
        fs.unlinkSync(path.resolve(root.absolute, ...publicOperation.stageRef.split("/")));
        fs.fsyncSync(parentHandle.descriptor);
      } finally {
        fs.closeSync(parentHandle.descriptor);
      }
      if (inspectMaintenanceFileState(root, privateOperation, publicOperation, step).state !== "committed") {
        fail("wakeflow-claude-settings-maintenance-cleanup", "cleanup did not leave exact final file");
      }
    },
  });
}

function directoryStepHandler(workspaceRoot, privateOperation, root, step) {
  let parentIdentity = null;
  const observe = () => {
    const directory = inspectSettingsDirectory(root.absolute);
    if (directory.state === "absent") {
      const absent = { ref: step.final.ref, type: "absent" };
      return { state: "initial", observation: { source: absent, staging: null, final: absent } };
    }
    if (directory.state === "directory" && directory.mode === "0700") {
      const current = { ref: step.final.ref, ...step.final };
      return { state: "committed", observation: { source: current, staging: null, final: current } };
    }
    return { state: "illegal", observation: null };
  };
  return Object.freeze({
    prepare(args) {
      const { context } = callbackArguments(args, ["context"], "Claude settings directory prepare arguments");
      assertMaintenanceContext(workspaceRoot, context);
      if (observe().state !== "initial") {
        fail("wakeflow-claude-settings-plan-stale", "settings directory changed before prepare");
      }
    },
    observe(args) {
      const { context } = callbackArguments(args, ["context"], "Claude settings directory observe arguments");
      assertMaintenanceContext(workspaceRoot, context);
      const inspected = observe();
      if (inspected.state === "illegal") {
        fail("wakeflow-claude-settings-maintenance-residue", "settings directory state is illegal");
      }
      const handle = openSafeDirectory(root.absolute);
      parentIdentity = handle.identity;
      fs.closeSync(handle.descriptor);
      return inspected.observation;
    },
    commit(args) {
      const { context } = callbackArguments(args, ["context"], "Claude settings directory commit arguments");
      assertMaintenanceContext(workspaceRoot, context);
      if (!parentIdentity || observe().state !== "initial") {
        fail("wakeflow-claude-settings-maintenance-race", "directory commit lacks exact observation");
      }
      const parentHandle = openSafeDirectory(root.absolute, parentIdentity);
      parentIdentity = null;
      try {
        if (observe().state !== "initial") {
          fail("wakeflow-claude-settings-maintenance-race", "settings directory changed after parent admission");
        }
        fs.mkdirSync(path.join(root.absolute, SETTINGS_DIRECTORY_REF), { mode: 0o700 });
        const targetHandle = openSafeDirectory(path.join(root.absolute, SETTINGS_DIRECTORY_REF));
        try {
          fs.fchmodSync(targetHandle.descriptor, 0o700);
          fs.fsyncSync(targetHandle.descriptor);
        } finally {
          fs.closeSync(targetHandle.descriptor);
        }
        fs.fsyncSync(parentHandle.descriptor);
      } catch (cause) {
        if (cause instanceof WakeflowClaudeSettingsError) throw cause;
        fail("wakeflow-claude-settings-maintenance-commit", "settings directory commit failed", {}, cause);
      } finally {
        fs.closeSync(parentHandle.descriptor);
      }
      if (observe().state !== "committed") {
        fail("wakeflow-claude-settings-maintenance-commit", "settings directory is not committed");
      }
    },
  });
}

function assertMaintenanceAuthority(input, confirmedPlan, context = null) {
  const snapshot = transitionSnapshot(input, context);
  if (
    snapshot.model.program.programId !== confirmedPlan.payload.programId
    || snapshot.configDigest !== confirmedPlan.payload.configDigest
  ) fail("wakeflow-claude-settings-plan-stale", "config authority differs from confirmed maintenance plan");
  return snapshot;
}

function reconstructMaintenancePrivateOperation({
  publicOperation,
  currentPrivateByDigest,
  root,
}) {
  const exact = currentPrivateByDigest.get(publicOperation.privateOperationDigest) ?? null;
  if (exact) return exact;
  const rootKey = `${publicOperation.root.rootKind}:${publicOperation.root.rootId}`;
  if (publicOperation.target.type === "directory") {
    return deepFreeze({
      operationId: operationId(rootKey, "settings-directory"),
      kind: "ensure-settings-directory",
      component: "settings-directory",
      root: publicOperation.root,
      ref: publicOperation.ref,
      source: { state: "absent" },
      desired: { mode: publicOperation.target.mode },
    });
  }
  const final = readStableFile(root.absolute, publicOperation.ref, {
    maximumBytes: operationMaximumBytes(publicOperation),
    label: `${publicOperation.component} recovery final`,
    allowedLinkCounts: [1, 2],
  });
  const stage = readStableFile(root.absolute, publicOperation.stageRef, {
    maximumBytes: operationMaximumBytes(publicOperation),
    label: `${publicOperation.component} recovery stage`,
    allowedLinkCounts: [1, 2],
  });
  if ([final.state, stage.state].includes("unsafe")) {
    fail("wakeflow-claude-settings-maintenance-residue", "recovery source or stage is unsafe");
  }
  const desiredSource = [stage, final].find((candidate) => (
    candidate.state === "file"
    && candidate.sha256 === publicOperation.target.digest
    && candidate.mode === publicOperation.target.mode
  )) ?? null;
  if (desiredSource === null) {
    fail("wakeflow-claude-settings-plan-stale", "recovery cannot reconstruct desired Claude settings bytes");
  }
  let source;
  if (publicOperation.source.type === "absent") {
    source = { state: "absent" };
  } else if (
    final.state === "file"
    && final.sha256 === publicOperation.source.digest
    && final.mode === publicOperation.source.mode
  ) {
    source = sourceExpectation(final);
  } else {
    source = {
      state: "file",
      sha256: publicOperation.source.digest,
      mode: publicOperation.source.mode,
      sourceIdentity: null,
    };
  }
  return deepFreeze({
    operationId: operationId(rootKey, publicOperation.component),
    kind: publicOperation.component === "statusline-asset"
      ? "write-managed-asset"
      : "write-mixed-owned-json",
    component: publicOperation.component,
    root: publicOperation.root,
    ref: publicOperation.ref,
    source,
    desired: {
      content: desiredSource.bytes,
      digest: publicOperation.target.digest,
      mode: publicOperation.target.mode,
    },
  });
}

function maintenancePhysicalState(privateOperation, publicOperation, root, step) {
  if (privateOperation.kind !== "ensure-settings-directory") {
    return inspectMaintenanceFileState(root, privateOperation, publicOperation, step).state;
  }
  const directory = inspectSettingsDirectory(root.absolute);
  if (directory.state === "absent") return "initial";
  if (directory.state === "directory" && directory.mode === publicOperation.target.mode) return "committed";
  return "illegal";
}

function prerequisiteOnlyMaintenanceTransition(current, confirmed) {
  if (current.payload.action !== confirmed.payload.action) return false;
  const withoutPrerequisiteObservation = (plan) => ({
    ...plan,
    payload: Object.fromEntries(Object.entries(plan.payload).filter(([key]) => (
      key !== "sourcePlanDigest" && key !== "diagnostics"
    ))),
  });
  return same(
    withoutPrerequisiteObservation(current),
    withoutPrerequisiteObservation(confirmed),
  );
}

/**
 * 从完整confirmed plan创建一次有界M3 participant。
 * participant在规划、每个物理阶段、恢复和terminal closure重新验证config/root authority。
 */
export function createClaudeSettingsAssetsMutationParticipant(value = {}) {
  const input = normalizeMaintenanceInput(value, { participant: true });
  const confirmedPlan = validateClaudeSettingsAssetsMaintenancePlan(input.confirmedPlan);
  if (
    confirmedPlan.payload.action !== input.action
    || !same(confirmedPlan.payload.authorizedRepositoryIds, input.authorizedRepositoryIds)
  ) {
    fail("wakeflow-claude-settings-plan-stale", "maintenance input differs from confirmed action or authorization");
  }
  const current = buildMaintenancePlan(input, null, { validateAuthority: false });
  if (confirmedPlan.payload.status !== "ready") {
    fail("wakeflow-claude-settings-blocked", "blocked Claude maintenance plan cannot create a participant");
  }
  const privatePlan = validateClaudeSettingsAssetsPlan(buildPlan(input, null, { validateAuthority: false }));
  const initialPlanExact = same(current, confirmedPlan);
  if (initialPlanExact && canonicalJsonDigest(privatePlan) !== confirmedPlan.payload.sourcePlanDigest) {
    fail("wakeflow-claude-settings-plan-stale", "private Claude settings plan differs from maintenance plan");
  }
  const currentPrivateByDigest = new Map(
    privatePlan.operations.map((operation) => [canonicalJsonDigest(operation), operation]),
  );
  const publicById = new Map(confirmedPlan.payload.operations.map((operation) => [operation.operationId, operation]));
  const snapshot = transitionSnapshot(input, null, { validateAuthority: false });
  const rootsById = new Map();
  const privateById = new Map();
  const stepHandlers = Object.fromEntries(confirmedPlan.payload.steps.map((step) => {
    const publicOperation = publicById.get(step.stepId);
    if (!publicOperation) {
      fail("wakeflow-claude-settings-maintenance-plan", "maintenance step lacks its private operation");
    }
    const root = rootForOperation(snapshot, publicOperation, input.authorizedRepositoryIds);
    const privateOperation = reconstructMaintenancePrivateOperation({
      publicOperation,
      currentPrivateByDigest,
      root,
    });
    rootsById.set(step.stepId, root);
    privateById.set(step.stepId, privateOperation);
    return [
      step.stepId,
      privateOperation.kind === "ensure-settings-directory"
        ? directoryStepHandler(input.workspaceRoot, privateOperation, root, step)
        : fileStepHandler(input.workspaceRoot, privateOperation, publicOperation, root, step),
    ];
  }));
  if (!initialPlanExact) {
    let recoveryBoundaryObserved = input.transition !== null
      && prerequisiteOnlyMaintenanceTransition(current, confirmedPlan);
    for (const step of confirmedPlan.payload.steps) {
      const publicOperation = publicById.get(step.stepId);
      const privateOperation = privateById.get(step.stepId);
      const state = maintenancePhysicalState(
        privateOperation,
        publicOperation,
        rootsById.get(step.stepId),
        step,
      );
      if (!new Set(["initial", "prepared", "committed", "committed-pair"]).has(state)) {
        fail("wakeflow-claude-settings-maintenance-residue", "confirmed plan differs at an illegal physical state");
      }
      const expectedPublic = publicMaintenanceOperation(privateOperation);
      const withoutPrivateDigest = (operation) => Object.fromEntries(
        Object.entries(operation).filter(([key]) => key !== "privateOperationDigest"),
      );
      if (!same(withoutPrivateDigest(expectedPublic), withoutPrivateDigest(publicOperation))) {
        fail("wakeflow-claude-settings-plan-stale", "recovery operation differs from its config-derived surface");
      }
      if (
        new Set(["initial", "prepared"]).has(state)
        && canonicalJsonDigest(privateOperation) !== publicOperation.privateOperationDigest
      ) {
        fail("wakeflow-claude-settings-plan-stale", "pending recovery operation differs from its private digest");
      }
      recoveryBoundaryObserved ||= state !== "initial";
    }
    if (!recoveryBoundaryObserved) {
      fail("wakeflow-claude-settings-plan-stale", "confirmed Claude maintenance plan is stale");
    }
  }

  return Object.freeze({
    validatePlan(args) {
      const { plan } = callbackArguments(args, ["plan"], "Claude settings validatePlan arguments");
      const candidate = validateClaudeSettingsAssetsMaintenancePlan(plan);
      if (!same(candidate, confirmedPlan)) {
        fail("wakeflow-claude-settings-maintenance-plan", "maintenance plan differs from participant contract");
      }
      return Object.freeze({ valid: true });
    },

    deriveCurrentPlan(args) {
      const { context } = callbackArguments(args, ["context"], "Claude settings deriveCurrentPlan arguments");
      if (context !== null) assertMaintenanceContext(input.workspaceRoot, context);
      assertMaintenanceAuthority(input, confirmedPlan, context);
      const recovery = context === null || context.recoveryGeneration > 0;
      if (!recovery) {
        const derived = buildMaintenancePlan(input, context);
        if (!same(derived, confirmedPlan)) {
          fail("wakeflow-claude-settings-plan-stale", "Claude maintenance source changed since confirmation");
        }
        return confirmedPlan;
      }
      for (const step of confirmedPlan.payload.steps) {
        const publicOperation = publicById.get(step.stepId);
        const privateOperation = privateById.get(step.stepId);
        const root = rootsById.get(step.stepId);
        const state = maintenancePhysicalState(privateOperation, publicOperation, root, step);
        if (!new Set(["initial", "prepared", "committed", "committed-pair"]).has(state)) {
          fail("wakeflow-claude-settings-maintenance-residue", "recovery observed illegal Claude settings residue");
        }
      }
      return confirmedPlan;
    },

    deriveTerminalClosure(args) {
      const { context, plan, planDigest } = callbackArguments(
        args,
        ["context", "plan", "planDigest"],
        "Claude settings terminal closure arguments",
      );
      assertMaintenanceContext(input.workspaceRoot, context);
      if (!same(plan, confirmedPlan) || planDigest !== canonicalJsonDigest(confirmedPlan)) {
        fail("wakeflow-claude-settings-maintenance-plan", "terminal closure received a different plan");
      }
      assertMaintenanceAuthority(input, confirmedPlan, context);
      const operations = confirmedPlan.payload.operations.map((publicOperation) => {
        const privateOperation = privateById.get(publicOperation.operationId);
        const root = rootForOperation(snapshot, privateOperation, input.authorizedRepositoryIds);
        if (privateOperation.kind === "ensure-settings-directory") {
          if (!operationSatisfied(privateOperation, root.absolute, input.workspaceRoot)) {
            fail("wakeflow-claude-settings-maintenance-terminal", "Claude settings directory is not terminal");
          }
        } else {
          const step = confirmedPlan.payload.steps.find((entry) => entry.stepId === publicOperation.operationId);
          const physical = inspectMaintenanceFileState(root, privateOperation, publicOperation, step);
          if (!new Set(["committed", "committed-pair"]).has(physical.state)) {
            fail("wakeflow-claude-settings-maintenance-terminal", "Claude settings file is not terminal");
          }
          if (privateOperation.component === "statusline-asset") {
            inspectClaudeStatuslineAssetRuntime({
              workspaceRoot: input.workspaceRoot,
              source: physical.state === "committed" ? "installed" : "template",
              stdin: "not-json",
            });
          }
        }
        return {
          operationId: publicOperation.operationId,
          resourceRef: publicOperation.resourceRef,
          targetDigest: publicOperation.target.digest,
        };
      });
      return {
        planDigest,
        closureDigests: [{
          name: "claude-settings-assets-closure",
          digest: canonicalJsonDigest({
            kind: "WakeflowClaudeSettingsAssetsClosure",
            schemaVersion: 1,
            programId: confirmedPlan.payload.programId,
            configDigest: confirmedPlan.payload.configDigest,
            authorizedRepositoryIds: confirmedPlan.payload.authorizedRepositoryIds,
            operations,
          }),
        }],
      };
    },

    stepHandlers: Object.freeze(stepHandlers),
  });
}

