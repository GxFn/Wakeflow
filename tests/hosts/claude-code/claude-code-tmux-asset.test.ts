test("tmux asset is a fixed 0600 file whose command and permission rule agree and which carries no paths or backticks", async (t) => {
  const current = await fixture(t);
  equal(statSync(current.assetPath).mode & 0o777, 0o600);
  equal(computeSha256Digest(readFileSync(current.assetPath)), CLAUDE_CODE_TMUX_ASSET_DIGEST);
  equal(readFileSync(current.assetPath, "utf8"), CLAUDE_CODE_TMUX_ASSET_CONTENT);
  equal(CLAUDE_CODE_TMUX_ASSET_CONTENT.includes("`"), false);
  equal(CLAUDE_CODE_TMUX_ASSET_CONTENT.includes("${"), false);
  equal(CLAUDE_CODE_TMUX_ASSET_CONTENT.includes("/Users/"), false);
  equal(CLAUDE_CODE_TMUX_ASSET_COMMAND, `node ${CLAUDE_CODE_TMUX_ASSET_REF}`);
  equal(WAKEFLOW_CLAUDE_CODE_TMUX_PERMISSION_RULE, `Bash(${CLAUDE_CODE_TMUX_ASSET_COMMAND} *)`);
  const rooted = await RootedDirectory.open(current.root);
  try {
    equal(await planClaudeCodeTmuxAssetOperation(rooted), null);
    writeFileSync(current.assetPath, `${CLAUDE_CODE_TMUX_ASSET_CONTENT}// drift\n`, { mode: 0o600 });
    const drifted = await planClaudeCodeTmuxAssetOperation(rooted);
    ok(drifted !== null, "byte drift must plan one operation");
    equal(drifted.operationId, CLAUDE_CODE_TMUX_ASSET_OPERATION_ID);
    equal(drifted.operationKind, "tmux-asset");
    equal(drifted.sourceDigest, computeSha256Digest(readFileSync(current.assetPath)));
    const updated = await executeClaudeCodeTmuxAssetOperation(rooted, {
      operation: drifted.payload,
      recoveringAffectedOperation: false,
    });
    equal(updated.disposition, "updated");
    equal(computeSha256Digest(readFileSync(current.assetPath)), CLAUDE_CODE_TMUX_ASSET_DIGEST);
  } finally {
    await rooted.close();
  }
});

