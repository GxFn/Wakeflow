test("桌面传输的渲染（ADR-0025 D3）：kind claude-code-desktop、desktop.title 与 cwd、没有 --session-id、sessionIdPolicy host-assigned、登记说明带 desktop.sessionId", () => {
  const raw = rawConfig();
  const controller = render(
    raw,
    claudeCodeDesktopWorkspaceHostResourceProfile,
    intentFor(raw, claudeCodeDesktopWorkspaceHostResourceProfile, CONTROLLER),
  );
  const expected = {
    kind: "claude-code-desktop",
    desktop: { title: "Controller", cwd: "." },
    command: "claude",
    arguments: [
      "--permission-mode",
      "auto",
      "--effort",
      "max",
      "--add-dir",
      "<workspace root>/../wakeflow-ledger",
    ],
    sessionIdPolicy: "host-assigned",
    registration: DESKTOP_REGISTRATION,
    worktree: null,
    attachedWorktrees: [],
  };
  deepEqual(controller, expected);
  equal(JSON.stringify(controller), JSON.stringify(expected), "key order is pinned");
  equal(JSON.stringify(controller).includes("--session-id"), false);
  equal(
    JSON.stringify(controller).includes("tmux"),
    false,
    "no tmux facts under the desktop transport",
  );
});

/** 去掉 tmux 独有的参数对（`--session-id <占位>`、`--worktree <名>`），剩下的就该是桌面参数。 */
function withoutTmuxOnlyArguments(value: unknown): readonly string[] {
  const list = value as readonly string[];
  const result: string[] = [];
  for (let index = 0; index < list.length; index += 1) {
    const argument = list[index] as string;
    if (argument === "--session-id" || argument === "--worktree") {
      index += 1;
      continue;
    }
    result.push(argument);
  }
  return result;
}

test("桌面与 tmux 对等：同一意图下 permission mode、effort、model 与 --add-dir 完全相同，标题等于 tmux 窗口名，cwd 相同，worktree 事实只有 note 不同（不许 --worktree）", () => {
  const cases: ReadonlyArray<readonly [Record<string, unknown>, string, boolean, Attached]> = [
    [rawConfig(LAUNCH_PREFERENCES), PRODUCT, false, []],
    [rawConfig(LAUNCH_PREFERENCES), PRODUCT, true, []],
    [rawConfig(), TEST_WINDOW, true, ATTACHED],
    [rawConfig(), CONTROLLER, true, []],
  ];
  for (const [raw, windowId, worktreePod, attached] of cases) {
    const tmuxIntent = intentFor(raw, claudeCodeWorkspaceHostResourceProfile, windowId);
    const desktopIntent = intentFor(raw, claudeCodeDesktopWorkspaceHostResourceProfile, windowId);
    const tmux = render(
      raw,
      claudeCodeWorkspaceHostResourceProfile,
      worktreePod ? asWorktreePod(tmuxIntent) : tmuxIntent,
      attached,
    );
    const desktop = render(
      raw,
      claudeCodeDesktopWorkspaceHostResourceProfile,
      worktreePod ? asWorktreePod(desktopIntent) : desktopIntent,
      attached,
    );
    const label = `${windowId} worktreePod=${worktreePod}`;
    deepEqual(desktop.arguments, withoutTmuxOnlyArguments(tmux.arguments), label);
    equal((desktop.arguments as readonly string[]).includes("--worktree"), false, label);
    const tmuxFacts = tmux.tmux as { readonly windowName: string; readonly cwd: string };
    deepEqual(desktop.desktop, { title: tmuxFacts.windowName, cwd: tmuxFacts.cwd }, label);
    deepEqual(desktop.attachedWorktrees, tmux.attachedWorktrees, label);
    if (tmux.worktree === null) {
      equal(desktop.worktree, null, label);
      continue;
    }
    const { note: tmuxNote, ...tmuxWorktree } = tmux.worktree as Record<string, unknown>;
    const { note: desktopNote, ...desktopWorktree } = desktop.worktree as Record<string, unknown>;
    deepEqual(desktopWorktree, tmuxWorktree, label);
    equal(typeof tmuxNote, "string");
    equal(
      desktopNote,
      "the desktop helper prepares the checkout at .claude/worktrees/<name> from the local HEAD (basePolicy local-head) and starts claude --bg with that checkout as the session cwd; never pass --worktree: the desktop app would claim the checkout as its own worktree and archiving the session would delete it",
      label,
    );
  }
});

