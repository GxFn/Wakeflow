/**
 * Wakeflow Host / Claude Code：状态栏资产（能力卡 9 §9.4 Q6，gate-log §13.94 D6）。
 *
 * 资产是一段由 Claude Code 状态栏调用的 Node 脚本：读 stdin 的 statusline JSON 取 `session_id`
 * 与模型名，读 `wakeflow.config.json` 与绑定目录找 `claude-session` 句柄等于 `session_id` 的窗口，
 * 打印恰好一行——main pod 为 `<model> · <window>`，其他 pod 为 `<model> · <pod> · <window>`，找不到
 * 只打印模型名；不含路径、句柄、摘要，stderr 为空。工作区根由命令行以 base64url 显式给出，
 * 从不从 cwd 推断。Wakeflow 只把字节写进自己的运行时目录并在 verify 里核对字节与模式，
 * 不 spawn node 做 smoke；`settings.local.json` 的 statusLine 条目由维护操作
 * `claude-statusline-settings:install` 写入（§13.94 D6 否决了"由 Agent 按计划安装"那条路径，
 * §13.96 记下落地机制），单键、CAS 与 0600 规则见 claude-code-statusline-settings-operation.ts。
 */

export const CLAUDE_CODE_STATUSLINE_ASSET_FILE_NAME = "statusline.mjs" as const;
export const CLAUDE_CODE_STATUSLINE_MARKER = "--wakeflow-statusline-v1" as const;
export const CLAUDE_CODE_STATUSLINE_ROOT_ARGUMENT = "--workspace-root-base64" as const;

export const CLAUDE_CODE_STATUSLINE_ASSET_REF: PortableResourcePath = parsePortableResourcePath(
  `${hostRuntimeRootRef("claude-code")}/operations/assets/${CLAUDE_CODE_STATUSLINE_ASSET_FILE_NAME}`,
  "$asset",
);

const SCRIPT_LINES: readonly string[] = [
  "#!/usr/bin/env node",
  "// Generated by Wakeflow. Claude Code statusline asset; do not edit.",
  "// wakeflow-statusline-schema: 2",
  'import { closeSync, constants, fstatSync, lstatSync, openSync, opendirSync, readSync } from "node:fs";',
  'import path from "node:path";',
  "",
  "const MAX_INPUT_BYTES = 262144;",
  "const MAX_CONFIG_BYTES = 1048576;",
  "const MAX_BINDING_BYTES = 65536;",
  "const MAX_BINDINGS = 4096;",
  "const MAX_LABEL = 128;",
  'const BINDINGS_DIRECTORY = ".wakeflow-local/runtime/hosts/claude-code/identity/window-bindings";',
  'const MARKER = "--wakeflow-statusline-v1";',
  'const ROOT_ARGUMENT = "--workspace-root-base64";',
  'const SEPARATOR = " · ";',
  "",
  "function isControl(codePoint) {",
  "  return codePoint < 0x20 || (codePoint >= 0x7f && codePoint <= 0x9f) || codePoint === 0x2028 || codePoint === 0x2029;",
  "}",
  "",
  "function cleanLabel(value, fallback) {",
  '  if (typeof value !== "string") return fallback;',
  '  let text = "";',
  '  for (const character of value) text += isControl(character.codePointAt(0) ?? 0) ? " " : character;',
  '  const cleaned = text.replace(/\\s+/gu, " ").trim();',
  "  return cleaned.length === 0 ? fallback : cleaned.slice(0, MAX_LABEL);",
  "}",
  "",
  "function readBoundedJson(file, maximumBytes) {",
  "  let descriptor = null;",
  "  try {",
  "    descriptor = openSync(file, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0));",
  "    const opened = fstatSync(descriptor);",
  "    if (!opened.isFile() || opened.size > maximumBytes) return null;",
  "    const bytes = Buffer.alloc(opened.size);",
  "    let offset = 0;",
  "    while (offset < bytes.length) {",
  "      const count = readSync(descriptor, bytes, offset, bytes.length - offset, null);",
  "      if (count === 0) break;",
  "      offset += count;",
  "    }",
  "    const after = lstatSync(file);",
  "    if (offset !== opened.size || after.ino !== opened.ino || after.size !== opened.size) return null;",
  '    return JSON.parse(new TextDecoder("utf-8", { fatal: true }).decode(bytes.subarray(0, offset)));',
  "  } catch {",
  "    return null;",
  "  } finally {",
  "    if (descriptor !== null) {",
  "      try {",
  "        closeSync(descriptor);",
  "      } catch {",
  "        // diagnostic read is already closed",
  "      }",
  "    }",
  "  }",
  "}",
  "",
  "function explicitWorkspaceRoot() {",
  "  const marker = process.argv.indexOf(MARKER);",
  "  if (marker < 0 || process.argv[marker + 1] !== ROOT_ARGUMENT) return null;",
  "  const encoded = process.argv[marker + 2];",
  '  if (typeof encoded !== "string" || !/^[A-Za-z0-9_-]+$/u.test(encoded)) return null;',
  "  try {",
  '    const decoded = Buffer.from(encoded, "base64url").toString("utf8");',
  '    if (decoded.length === 0 || Buffer.from(decoded, "utf8").toString("base64url") !== encoded) return null;',
  "    if (!path.isAbsolute(decoded) || path.resolve(decoded) !== decoded) return null;",
  "    return decoded;",
  "  } catch {",
  "    return null;",
  "  }",
  "}",
  "",
  "function readConfig(root) {",
  '  const parsed = readBoundedJson(path.join(root, "wakeflow.config.json"), MAX_CONFIG_BYTES);',
  // 配置身份来自词汇层：脚本文本在模块加载时定型，字节仍是确定的。
  `  if (parsed === null || typeof parsed !== "object" || parsed.kind !== ${JSON.stringify(WAKEFLOW_CONFIG_KIND)} || parsed.schemaVersion !== ${WAKEFLOW_CONFIG_SCHEMA_VERSION}) return null;`,
  "  if (!Array.isArray(parsed.topology?.windows) || !Array.isArray(parsed.pods)) return null;",
  "  return parsed;",
  "}",
  "",
  "function windowIdForSession(root, config, sessionId) {",
  '  if (typeof sessionId !== "string" || sessionId.length === 0) return null;',
  "  let directory = null;",
  "  try {",
  "    directory = opendirSync(path.join(root, ...BINDINGS_DIRECTORY.split(\"/\")));",
  "    const names = [];",
  "    let observed = 0;",
  "    for (;;) {",
  "      const entry = directory.readSync();",
  "      if (entry === null) break;",
  "      observed += 1;",
  "      if (observed > MAX_BINDINGS) return null;",
  '      if (entry.isFile() && entry.name.endsWith(".json")) names.push(entry.name);',
  "    }",
  "    names.sort();",
  "    for (const name of names) {",
  "      const record = readBoundedJson(path.join(root, ...BINDINGS_DIRECTORY.split(\"/\"), name), MAX_BINDING_BYTES);",
  "      if (",
  '        record?.kind === "WakeflowWindowHostBinding" &&',
  "        record?.schemaVersion === 1 &&",
  "        record?.programId === config?.program?.programId &&",
  '        record?.hostId === "claude-code" &&',
  '        record?.handle?.kind === "claude-session" &&',
  "        record?.handle?.value === sessionId &&",
  '        typeof record?.windowId === "string"',
  "      ) {",
  "        return record.windowId;",
  "      }",
  "    }",
  "  } catch {",
  "    return null;",
  "  } finally {",
  "    if (directory !== null) {",
  "      try {",
  "        directory.closeSync();",
  "      } catch {",
  "        // diagnostic enumeration is already closed",
  "      }",
  "    }",
  "  }",
  "  return null;",
  "}",
  "",
  "function labelFor(config, windowId) {",
  "  const window = config.topology.windows.find((entry) => entry?.windowId === windowId);",
  "  if (window === undefined) return null;",
  '  const windowLabel = cleanLabel(window.displayName, "window");',
  "  const pod = config.pods.find((entry) => entry?.podId === window.podId);",
  '  if (pod === undefined || pod.placement === "primary") return windowLabel;',
  '  return cleanLabel(pod.name, "pod") + SEPARATOR + windowLabel;',
  "}",
  "",
  "function readStdin() {",
  "  const chunks = [];",
  "  let total = 0;",
  "  const buffer = Buffer.alloc(65536);",
  "  for (;;) {",
  "    let count = 0;",
  "    try {",
  "      count = readSync(0, buffer, 0, buffer.length, null);",
  "    } catch (error) {",
  '      if (error?.code === "EAGAIN") continue;',
  "      break;",
  "    }",
  "    if (count === 0) break;",
  "    total += count;",
  "    if (total > MAX_INPUT_BYTES) return null;",
  "    chunks.push(Buffer.from(buffer.subarray(0, count)));",
  "  }",
  "  try {",
  '    return JSON.parse(new TextDecoder("utf-8", { fatal: true }).decode(Buffer.concat(chunks)));',
  "  } catch {",
  "    return null;",
  "  }",
  "}",
  "",
  "function main() {",
  "  const input = readStdin();",
  '  const model = cleanLabel(input?.model?.display_name ?? input?.model?.id, "Claude");',
  "  const root = explicitWorkspaceRoot();",
  "  const config = root === null ? null : readConfig(root);",
  "  const windowId = config === null ? null : windowIdForSession(root, config, input?.session_id);",
  "  const label = windowId === null ? null : labelFor(config, windowId);",
  '  process.stdout.write((label === null ? model : model + SEPARATOR + label) + "\\n");',
  "}",
  "",
  "main();",
];

/** 资产的精确字节：维护事务写入的就是这一份，verify 按它核对。 */
export const CLAUDE_CODE_STATUSLINE_ASSET_CONTENT: string = `${SCRIPT_LINES.join("\n")}\n`;

export const CLAUDE_CODE_STATUSLINE_ASSET_DIGEST: Sha256Digest = computeSha256Digest(
  encodeUtf8(CLAUDE_CODE_STATUSLINE_ASSET_CONTENT, "$asset"),
  "$asset",
);

function shellQuote(value: string): string {
  return `'${value.replace(/'/gu, "'\\''")}'`;
}

/**
 * 维护操作 `claude-statusline-settings:install` 写进 `settings.local.json` 的
 * `statusLine.command`：根以 base64url 显式传入。唯一调用方是
 * claude-code-statusline-settings-operation.ts 的 `claudeCodeStatuslineSettingsEntry`，
 * 那里定义只改 `statusLine` 一键、CAS 替换与 0600 的规则；改命令形状要同时改那条操作的目标摘要。
 */
export function claudeCodeStatuslineCommand(workspaceRoot: string): string {
  const asset = [workspaceRoot, ...CLAUDE_CODE_STATUSLINE_ASSET_REF.split("/")].join("/");
  const encodedRoot = Buffer.from(workspaceRoot, "utf8").toString("base64url");
  return `node -- ${shellQuote(asset)} ${CLAUDE_CODE_STATUSLINE_MARKER} ${CLAUDE_CODE_STATUSLINE_ROOT_ARGUMENT} ${encodedRoot}`;
}
