function maintenanceToken(value) {
  return `claude-settings-${createHashHex(canonicalJson(value)).slice(0, 32)}`;
}

function createHashHex(value) {
  return sha256Bytes(Buffer.from(value, "utf8"));
}

function maintenancePlacementToken(value) {
  return createHashHex(value).slice(0, 16);
}

function maintenanceResourceRef(operation) {
  return `targets/${operation.root.rootKind}/${operation.root.rootId}/${maintenancePlacementToken(
    operation.root.configuredPath,
  )}/${operation.ref}`;
}

function maintenanceSourceNode(operation) {
  if (operation.source.state === "absent") return { type: "absent" };
  return {
    type: "file",
    mode: operation.source.mode,
    digest: operation.source.sha256,
  };
}

function maintenanceTargetNode(operation) {
  if (operation.kind === "ensure-settings-directory") {
    return {
      type: "directory",
      mode: operation.desired.mode,
      digest: canonicalJsonDigest({
        kind: "WakeflowClaudeSettingsDirectoryTarget",
        schemaVersion: 1,
        root: operation.root,
        ref: operation.ref,
        mode: operation.desired.mode,
      }),
    };
  }
  return {
    type: "file",
    mode: operation.desired.mode,
    digest: operation.desired.digest,
  };
}

function maintenanceStageRef(operationId, operation) {
  if (operation.kind === "ensure-settings-directory") return null;
  const directory = path.posix.dirname(operation.ref);
  const file = `.${operationId}.${operation.desired.digest.slice("sha256:".length, "sha256:".length + 16)}.stage`;
  return directory === "." ? file : `${directory}/${file}`;
}

function publicMaintenanceOperation(operation) {
  const operationId = maintenanceToken({
    privateOperationId: operation.operationId,
    root: operation.root,
    ref: operation.ref,
  });
  const source = maintenanceSourceNode(operation);
  return {
    operationId,
    privateOperationDigest: canonicalJsonDigest(operation),
    component: operation.component,
    owner: MAINTENANCE_OWNER,
    root: operation.root,
    ref: operation.ref,
    resourceRef: maintenanceResourceRef(operation),
    classification: source.type === "absent" ? "managed-missing" : "managed-stale-known",
    source,
    target: maintenanceTargetNode(operation),
    action: source.type === "absent" ? "create-managed" : "update-managed",
    reasonCode: operation.kind === "ensure-settings-directory"
      ? "claude-settings-directory-create"
      : "claude-settings-content-refresh",
    stageRef: maintenanceStageRef(operationId, operation),
  };
}

function maintenanceStep(operation, ordinal) {
  const base = {
    stepId: operation.operationId,
    ordinal,
    stepKind: "create-or-update",
    source: { ref: operation.resourceRef, ...operation.source },
    final: { ref: operation.resourceRef, ...operation.target },
  };
  if (operation.target.type === "directory") return { ...base, staging: null };
  return {
    ...base,
    staging: {
      ref: `${path.posix.dirname(operation.resourceRef)}/${path.posix.basename(operation.stageRef)}`,
      ...operation.target,
    },
  };
}

function maintenanceBlocker(value, index) {
  const subjectDigest = canonicalJsonDigest({ value });
  return {
    blockerId: `claude-settings-blocker-${String(index).padStart(4, "0")}`,
    code: "claude-settings-source-blocked",
    subjectDigest,
  };
}

function inspectMaintenanceStage(rootAbsolute, operation) {
  const stageRef = maintenanceStageRef(
    maintenanceToken({
      privateOperationId: operation.operationId,
      root: operation.root,
      ref: operation.ref,
    }),
    operation,
  );
  if (stageRef === null) return { state: "absent" };
  return readStableFile(rootAbsolute, stageRef, {
    maximumBytes: operation.component === "statusline-asset" ? MAX_ASSET_BYTES : MAX_SETTINGS_BYTES,
    label: `${operation.component} maintenance stage`,
    allowedLinkCounts: [1, 2],
  });
}

function buildMaintenancePlan(input, context = null, options = undefined) {
  const privatePlan = validateClaudeSettingsAssetsPlan(buildPlan(input, context, options));
  const operations = privatePlan.operations.map(publicMaintenanceOperation);
  const blockers = privatePlan.blockers.map(maintenanceBlocker);
  const snapshot = transitionSnapshot(input, context, options);
  for (const [index, privateOperation] of privatePlan.operations.entries()) {
    if (privateOperation.kind === "ensure-settings-directory") continue;
    const root = rootForOperation(snapshot, privateOperation, input.authorizedRepositoryIds);
    const plannedMissingRoot = privateOperation.root.rootKind === "support-surface"
      && input.transition?.plannedSupportSurfaceIds.includes(privateOperation.root.rootId)
      && (() => {
        try {
          fs.lstatSync(root.absolute);
          return false;
        } catch (cause) {
          return cause?.code === "ENOENT";
        }
      })();
    if (plannedMissingRoot) continue;
    const stage = inspectMaintenanceStage(root.absolute, privateOperation);
    if (stage.state !== "absent") {
      blockers.push({
        blockerId: `claude-settings-stage-${String(index).padStart(4, "0")}`,
        code: "claude-settings-stage-residue",
        subjectDigest: canonicalJsonDigest({
          operationId: operations[index].operationId,
          stageState: stage.state,
        }),
      });
    }
  }
  blockers.sort((left, right) => lexicalCompare(left.blockerId, right.blockerId));
  const status = blockers.length === 0 ? "ready" : "blocked";
  const steps = status === "ready"
    ? operations.map((operation, ordinal) => maintenanceStep(operation, ordinal))
    : [];
  return validateClaudeSettingsAssetsMaintenancePlan({
    schemaId: WAKEFLOW_CLAUDE_SETTINGS_MAINTENANCE_SCHEMA_ID,
    payload: {
      kind: WAKEFLOW_CLAUDE_SETTINGS_MAINTENANCE_KIND,
      schemaVersion: WAKEFLOW_CLAUDE_SETTINGS_MAINTENANCE_SCHEMA_VERSION,
      action: input.action,
      status,
      programId: privatePlan.programId,
      configDigest: privatePlan.configDigest,
      hostId: HOST_ID,
      authorizedRepositoryIds: input.authorizedRepositoryIds,
      sourcePlanDigest: canonicalJsonDigest(privatePlan),
      operations,
      blockers,
      diagnostics: privatePlan.diagnostics,
      steps,
    },
  });
}

function canonicalStringArray(value, label, normalizeEntry) {
  exactDataArray(value, label);
  const normalized = value.map(normalizeEntry).sort(lexicalCompare);
  if (new Set(normalized).size !== normalized.length || !same(value, normalized)) {
    fail("wakeflow-claude-settings-contract", `${label} must be unique and canonical`);
  }
  return Object.freeze(normalized);
}

function normalizeTransition(value, action) {
  const sourceModel = value.sourceModel === null
    ? null
    : parseWakeflowConfigV3(value.sourceModel);
  const desiredModel = parseWakeflowConfigV3(value.desiredModel);
  if (
    (action === "fresh-initialize") !== (sourceModel === null)
    || (sourceModel !== null && sourceModel.program.programId !== desiredModel.program.programId)
    || (
      action === "reconcile"
      && wakeflowConfigV3Digest(sourceModel) !== wakeflowConfigV3Digest(desiredModel)
    )
  ) fail("wakeflow-claude-settings-contract", "Claude settings transition models do not match the action");
  const managedSurfaceIds = new Set(desiredModel.topology.supportSurfaces
    .filter((entry) => entry.ownership === "wakeflow-managed")
    .map((entry) => entry.surfaceId));
  const plannedSupportSurfaceIds = canonicalStringArray(
    value.plannedSupportSurfaceIds,
    "plannedSupportSurfaceIds",
    (entry, index) => {
      const surfaceId = typedId(entry, "surface", `plannedSupportSurfaceIds/${index}`);
      if (!managedSurfaceIds.has(surfaceId)) {
        fail("wakeflow-claude-settings-contract", "planned support surface is not desired Wakeflow-managed topology", {
          surfaceId,
        });
      }
      return surfaceId;
    },
  );
  const plannedLocalDirectoryRefs = canonicalStringArray(
    value.plannedLocalDirectoryRefs,
    "plannedLocalDirectoryRefs",
    (entry, index) => portableRef(entry, `plannedLocalDirectoryRefs/${index}`),
  );
  const allowedRootKeys = new Set([
    `program:${desiredModel.program.programId}`,
    ...desiredModel.topology.supportSurfaces.map((entry) => `support-surface:${entry.surfaceId}`),
    ...desiredModel.topology.repositories.map((entry) => `repository:${entry.repositoryId}`),
  ]);
  const plannedIgnoreRootKeys = canonicalStringArray(
    value.plannedIgnoreRootKeys,
    "plannedIgnoreRootKeys",
    (entry) => {
      if (typeof entry !== "string" || !allowedRootKeys.has(entry)) {
        fail("wakeflow-claude-settings-contract", "plannedIgnoreRootKeys contains an unknown desired root");
      }
      return entry;
    },
  );
  return deepFreeze({
    sourceModel,
    desiredModel,
    plannedSupportSurfaceIds,
    plannedLocalDirectoryRefs,
    plannedIgnoreRootKeys,
  });
}

function normalizeMaintenanceInput(value, { participant = false } = {}) {
  const base = ["workspaceRoot", "action", "authorizedRepositoryIds"];
  const transitionFields = [
    "sourceModel",
    "desiredModel",
    "plannedSupportSurfaceIds",
    "plannedLocalDirectoryRefs",
    "plannedIgnoreRootKeys",
  ];
  const actual = plainObject(value) ? Reflect.ownKeys(value) : [];
  const hasTransition = transitionFields.some((field) => Object.hasOwn(value ?? {}, field));
  const expected = [
    ...base,
    ...(hasTransition ? transitionFields : []),
    ...(participant ? ["confirmedPlan"] : []),
  ];
  exactDataObject(
    value,
    expected,
    [],
    participant ? "Claude settings maintenance participant input" : "Claude settings maintenance plan input",
  );
  if (!MAINTENANCE_ACTIONS.has(value.action)) {
    fail("wakeflow-claude-settings-contract", "Claude settings maintenance action is invalid");
  }
  if (!hasTransition && value.action === "fresh-initialize") {
    fail("wakeflow-claude-settings-contract", "fresh Claude settings maintenance requires exact transition models");
  }
  if (actual.length !== expected.length) {
    fail("wakeflow-claude-settings-contract", "Claude settings maintenance input is incomplete");
  }
  return {
    workspaceRoot: normalizeRoot(value.workspaceRoot),
    action: value.action,
    authorizedRepositoryIds: normalizeAuthorizedRepositoryIds(value.authorizedRepositoryIds),
    transition: hasTransition ? normalizeTransition(value, value.action) : null,
    ...(participant ? { confirmedPlan: value.confirmedPlan } : {}),
  };
}

function validateMaintenanceNode(value, label) {
  if (!plainObject(value) || typeof value.type !== "string") {
    fail("wakeflow-claude-settings-maintenance-plan", `${label} must be one resource node`);
  }
  if (value.type === "absent") {
    exactDataObject(value, ["type"], [], label);
    return value;
  }
  exactDataObject(value, ["type", "mode", "digest"], [], label);
  if (!new Set(["file", "directory"]).has(value.type) || !MODE_RE.test(value.mode) || !DIGEST_RE.test(value.digest)) {
    fail("wakeflow-claude-settings-maintenance-plan", `${label} is invalid`);
  }
  return value;
}

function validateConfiguredPath(value, label) {
  if (
    typeof value !== "string"
    || !value
    || value !== value.trim()
    || CONTROL_RE.test(value)
    || value.includes("\\")
    || path.posix.isAbsolute(value)
    || path.posix.normalize(value) !== value
  ) fail("wakeflow-claude-settings-maintenance-plan", `${label} is not one canonical configured path`);
  return value;
}

// 公开 maintenance operation 必须能从 component、root、source 和 target 相互重建。
function validateMaintenanceOperationSemantics(operation, payload, rootPaths) {
  const spec = typeof operation.component === "string" && Object.hasOwn(MAINTENANCE_COMPONENTS, operation.component)
    ? MAINTENANCE_COMPONENTS[operation.component]
    : null;
  if (spec === null) {
    fail("wakeflow-claude-settings-maintenance-plan", "maintenance component is invalid");
  }
  const rootKind = operation.root.rootKind;
  const idType = rootKind === "program"
    ? "program"
    : rootKind === "repository"
      ? "repository"
      : rootKind === "support-surface"
        ? "surface"
        : null;
  if (idType === null) {
    fail("wakeflow-claude-settings-maintenance-plan", "maintenance root kind is invalid");
  }
  typedId(operation.root.rootId, idType, `maintenance/root/${rootKind}`);
  validateConfiguredPath(operation.root.configuredPath, "maintenance root configuredPath");
  if (
    rootKind === "program"
    && (
      operation.root.rootId !== payload.programId
      || operation.root.configuredPath !== "."
    )
  ) fail("wakeflow-claude-settings-maintenance-plan", "program operation root differs from the payload program");
  if (
    rootKind === "repository"
    && !payload.authorizedRepositoryIds.includes(operation.root.rootId)
  ) fail("wakeflow-claude-settings-maintenance-plan", "repository operation is not in the authorization set");
  if (spec.programOnly && rootKind !== "program") {
    fail("wakeflow-claude-settings-maintenance-plan", "statusline asset must stay in the program root");
  }
  const rootKey = `${rootKind}:${operation.root.rootId}`;
  const priorPath = rootPaths.get(rootKey);
  if (priorPath !== undefined && priorPath !== operation.root.configuredPath) {
    fail("wakeflow-claude-settings-maintenance-plan", "one root identity has multiple configured paths");
  }
  rootPaths.set(rootKey, operation.root.configuredPath);

  if (
    operation.ref !== spec.ref
    || operation.target.type !== spec.targetType
    || operation.target.mode !== spec.mode
    || operation.reasonCode !== spec.reasonCode
    || !new Set(["absent", "file"]).has(operation.source.type)
  ) fail("wakeflow-claude-settings-maintenance-plan", "maintenance component resource matrix is invalid");

  const missing = operation.source.type === "absent";
  if (
    operation.classification !== (missing ? "managed-missing" : "managed-stale-known")
    || operation.action !== (missing ? "create-managed" : "update-managed")
  ) fail("wakeflow-claude-settings-maintenance-plan", "maintenance source classification or action is invalid");

  const expectedOperationId = maintenanceToken({
    privateOperationId: operationId(rootKey, operation.component),
    root: operation.root,
    ref: operation.ref,
  });
  if (
    operation.operationId !== expectedOperationId
    || operation.resourceRef !== maintenanceResourceRef(operation)
  ) fail("wakeflow-claude-settings-maintenance-plan", "maintenance operation identity or resourceRef is not derived");

  const privateShape = {
    kind: spec.privateKind,
    ref: operation.ref,
    root: operation.root,
    desired: {
      mode: operation.target.mode,
      ...(operation.target.type === "file" ? { digest: operation.target.digest } : {}),
    },
  };
  const expectedStageRef = maintenanceStageRef(operation.operationId, privateShape);
  if (operation.stageRef !== expectedStageRef) {
    fail("wakeflow-claude-settings-maintenance-plan", "maintenance stageRef is not operation-derived");
  }
  if (operation.target.type === "directory") {
    const expectedTarget = maintenanceTargetNode(privateShape);
    if (!same(operation.target, expectedTarget)) {
      fail("wakeflow-claude-settings-maintenance-plan", "maintenance directory target digest is not derived");
    }
  }
}

/** 校验脱敏 maintenance plan 的identity、operation矩阵、blocker和step闭包。 */
export function validateClaudeSettingsAssetsMaintenancePlan(value) {
  const plan = cloneFrozen(value);
  exactDataObject(plan, ["schemaId", "payload"], [], "Claude settings maintenance plan");
  if (plan.schemaId !== WAKEFLOW_CLAUDE_SETTINGS_MAINTENANCE_SCHEMA_ID) {
    fail("wakeflow-claude-settings-maintenance-plan", "Claude settings maintenance schemaId is invalid");
  }
  exactDataObject(plan.payload, [
    "kind",
    "schemaVersion",
    "action",
    "status",
    "programId",
    "configDigest",
    "hostId",
    "authorizedRepositoryIds",
    "sourcePlanDigest",
    "operations",
    "blockers",
    "diagnostics",
    "steps",
  ], [], "Claude settings maintenance payload");
  const payload = plan.payload;
  if (
    payload.kind !== WAKEFLOW_CLAUDE_SETTINGS_MAINTENANCE_KIND
    || payload.schemaVersion !== WAKEFLOW_CLAUDE_SETTINGS_MAINTENANCE_SCHEMA_VERSION
    || !MAINTENANCE_ACTIONS.has(payload.action)
    || !new Set(["ready", "blocked"]).has(payload.status)
    || payload.hostId !== HOST_ID
  ) fail("wakeflow-claude-settings-maintenance-plan", "Claude settings maintenance identity is invalid");
  typedId(payload.programId, "program", "maintenance/programId");
  if (!DIGEST_RE.test(payload.configDigest) || !DIGEST_RE.test(payload.sourcePlanDigest)) {
    fail("wakeflow-claude-settings-maintenance-plan", "Claude settings maintenance digest is invalid");
  }
  const normalizedAuthorizedRepositoryIds = normalizeAuthorizedRepositoryIds(payload.authorizedRepositoryIds);
  if (!same(payload.authorizedRepositoryIds, normalizedAuthorizedRepositoryIds)) {
    fail("wakeflow-claude-settings-maintenance-plan", "authorizedRepositoryIds are not canonical");
  }
  if (
    !Array.isArray(payload.operations)
    || !Array.isArray(payload.blockers)
    || !Array.isArray(payload.diagnostics)
    || !Array.isArray(payload.steps)
  ) fail("wakeflow-claude-settings-maintenance-plan", "Claude settings maintenance collections are invalid");
  assertStringArray(payload.diagnostics, "maintenance diagnostics");
  const normalizedDiagnostics = [...payload.diagnostics].sort(lexicalCompare);
  if (
    new Set(normalizedDiagnostics).size !== normalizedDiagnostics.length
    || !same(payload.diagnostics, normalizedDiagnostics)
  ) fail("wakeflow-claude-settings-maintenance-plan", "maintenance diagnostics must be unique and canonical");
  const operationIds = new Set();
  const rootPaths = new Map();
  for (const operation of payload.operations) {
    exactDataObject(operation, [
      "operationId",
      "privateOperationDigest",
      "component",
      "owner",
      "root",
      "ref",
      "resourceRef",
      "classification",
      "source",
      "target",
      "action",
      "reasonCode",
      "stageRef",
    ], [], "Claude settings maintenance operation");
    if (
      typeof operation.operationId !== "string"
      || !/^claude-settings-[0-9a-f]{32}$/u.test(operation.operationId)
      || operationIds.has(operation.operationId)
      || !DIGEST_RE.test(operation.privateOperationDigest)
      || operation.owner !== MAINTENANCE_OWNER
      || !new Set(["managed-missing", "managed-stale-known"]).has(operation.classification)
      || !MAINTENANCE_PHYSICAL_ACTIONS.has(operation.action)
    ) fail("wakeflow-claude-settings-maintenance-plan", "Claude settings maintenance operation is invalid");
    operationIds.add(operation.operationId);
    exactDataObject(operation.root, ["rootKind", "rootId", "configuredPath"], [], "maintenance root");
    portableRef(operation.ref, "maintenance operation ref");
    portableRef(operation.resourceRef, "maintenance resource ref");
    validateMaintenanceNode(operation.source, "maintenance source");
    validateMaintenanceNode(operation.target, "maintenance target");
    if (operation.target.type === "directory") {
      if (operation.stageRef !== null) {
        fail("wakeflow-claude-settings-maintenance-plan", "directory operation cannot have staging");
      }
    } else portableRef(operation.stageRef, "maintenance stage ref");
    validateMaintenanceOperationSemantics(operation, payload, rootPaths);
  }
  const blockerIds = new Set();
  for (const blocker of payload.blockers) {
    exactDataObject(blocker, ["blockerId", "code", "subjectDigest"], [], "maintenance blocker");
    if (
      typeof blocker.blockerId !== "string"
      || blockerIds.has(blocker.blockerId)
      || !new Set(["claude-settings-source-blocked", "claude-settings-stage-residue"]).has(blocker.code)
      || !DIGEST_RE.test(blocker.subjectDigest)
    ) fail("wakeflow-claude-settings-maintenance-plan", "maintenance blocker is invalid");
    blockerIds.add(blocker.blockerId);
    const expectedPrefix = blocker.code === "claude-settings-source-blocked"
      ? "claude-settings-blocker-"
      : "claude-settings-stage-";
    if (!new RegExp(`^${expectedPrefix}[0-9]{4}$`, "u").test(blocker.blockerId)) {
      fail("wakeflow-claude-settings-maintenance-plan", "maintenance blocker identity differs from its code");
    }
  }
  if (!same(payload.blockers, [...payload.blockers].sort((left, right) => lexicalCompare(left.blockerId, right.blockerId)))) {
    fail("wakeflow-claude-settings-maintenance-plan", "maintenance blockers must use canonical order");
  }
  const expectedSteps = payload.status === "ready"
    ? payload.operations.map((operation, ordinal) => maintenanceStep(operation, ordinal))
    : [];
  if (!same(payload.steps, expectedSteps) || payload.status !== (payload.blockers.length === 0 ? "ready" : "blocked")) {
    fail("wakeflow-claude-settings-maintenance-plan", "maintenance status or steps are not derived");
  }
  return plan;
}

