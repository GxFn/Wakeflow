// --bg 的输出："backgrounded · <短 id> · <名字>"；也接受直接打印完整 uuid 的形态。
function parseBackgroundId(output) {
  const text = stripSgr(output);
  const line = text.split(/\r?\n/u).find((entry) => BACKGROUNDED_PATTERN.test(entry)) ?? "";
  const words = line.split(/[\s·•|:]+/u).filter((word) => word.length > 0);
  const uuid = words.find((word) => UUID_PATTERN.test(word));
  if (uuid !== undefined) return uuid;
  const index = words.findIndex((word) => BACKGROUNDED_PATTERN.test(word));
  const candidate = words[index + 1];
  if (index !== -1 && candidate !== undefined && SHORT_ID_PATTERN.test(candidate)) return candidate;
  refuse("launch-id-unparsed", { detail: boundedDetail(text) });
}

