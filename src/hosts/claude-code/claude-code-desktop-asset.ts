function parseArguments(argv) {
  const [command, ...rest] = argv;
  const options = {
    window: null,
    force: false,
    wait: DEFAULT_FIRST_TURN_WAIT_SECONDS,
    waitSessionStart: DEFAULT_SESSION_START_WAIT_SECONDS,
    waitLanding: DEFAULT_LANDING_WAIT_SECONDS,
    promptDigest: null,
  };
  for (let index = 0; index < rest.length; index += 1) {
    const argument = rest[index];
    if (argument === "--force") {
      options.force = true;
    } else if (argument === "--window") {
      options.window = parseWindowId(rest[index + 1], "--window");
      index += 1;
    } else if (argument === "--wait") {
      options.wait = parseSeconds(rest[index + 1], "wait-invalid");
      index += 1;
    } else if (argument === "--wait-session-start") {
      options.waitSessionStart = parseSeconds(rest[index + 1], "wait-session-start-invalid");
      index += 1;
    } else if (argument === "--wait-landing") {
      options.waitLanding = parseSeconds(rest[index + 1], "wait-landing-invalid");
      index += 1;
    } else if (argument === "--prompt-digest") {
      const digest = rest[index + 1];
      if (typeof digest !== "string" || !DIGEST_PATTERN.test(digest)) refuse("prompt-digest-invalid");
      options.promptDigest = digest;
      index += 1;
    } else {
      refuse("argument-unknown");
    }
  }
  return Object.freeze({ command: command ?? null, options: Object.freeze(options) });
}

function unwrapIntent(input, options) {
  const wrapped = typeof input.launchIntent === "object" && input.launchIntent !== null;
  const intent = wrapped ? input.launchIntent : input;
  // inspect 结果的意图自带 role；更早的结果只在顶层带 role，仍接受（§13.182 F-L1-8）。意图里的优先。
  const launchIntent = typeof intent.role !== "string" && wrapped && typeof input.role === "string"
    ? Object.freeze({ ...intent, role: input.role })
    : intent;
  const windowId = options.window ?? (typeof input.windowId === "string" ? input.windowId : null);
  if (windowId === null) refuse("window-required");
  parseWindowId(windowId, "--window");
  if (typeof launchIntent.intentDigest !== "string" || !DIGEST_PATTERN.test(launchIntent.intentDigest)) {
    refuse("intent-invalid", { field: "intentDigest" });
  }
  // role 决定许可规则，属于意图接纳：在任何宿主调用之前拒绝。
  if (!knownRole(launchIntent.role)) refuse("intent-invalid", { field: "role" });
  return Object.freeze({ windowId, launchIntent });
}

