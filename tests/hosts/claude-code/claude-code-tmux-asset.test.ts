const TMUX_STUB = `#!/bin/bash
set -u
state="$WAKEFLOW_STUB_STATE"
log="$WAKEFLOW_STUB_LOG"
if [ "\${1:-}" = "-L" ]; then shift 2; fi
cmd="\${1:-}"
shift || true
{ printf '%s' "$cmd"; for arg in "$@"; do printf '\\x1f%s' "$arg"; done; printf '\\n'; } >> "$log"
if [ "\${WAKEFLOW_STUB_FAIL:-}" = "$cmd" ]; then exit 1; fi
case "$cmd" in
  -V) echo "tmux 3.6b" ;;
  has-session) [ -e "$state/session" ] ;;
  new-session|new-window)
    touch "$state/session"
    n=$(cat "$state/counter" 2>/dev/null || echo 0); n=$((n + 1)); echo "$n" > "$state/counter"
    if [ -n "\${WAKEFLOW_STUB_HOOKS:-}" ]; then
      cwd=""; prev=""
      for arg in "$@"; do
        if [ "$prev" = "-c" ]; then cwd="$arg"; fi
        prev="$arg"
      done
      last="\${!#}"
      sid=$(printf '%s' "$last" | sed -n "s/.*'--session-id' '\\([^']*\\)'.*/\\1/p")
      if [ -n "$sid" ]; then
        printf '{"kind":"stub","event":"session-start","sessionId":"%s","cwd":"%s"}\\n' "$sid" "$cwd" > "$WAKEFLOW_STUB_HOOKS/20260924T000000000Z-session-start-$sid.json"
      fi
      rid=$(printf '%s' "$last" | sed -n "s/.*'--resume' '\\([^']*\\)'.*/\\1/p")
      if [ -n "$rid" ]; then
        printf '{"kind":"stub","event":"session-start","sessionId":"%s","cwd":"%s","source":"resume"}\\n' "$rid" "$cwd" > "$WAKEFLOW_STUB_HOOKS/20260924T000001000Z-session-start-resume-$rid.json"
      fi
    fi
    printf '@%s~|~%%%s\\n' "$n" "$n" ;;
  set-option|paste-buffer|send-keys|delete-buffer) : ;;
  list-panes) if [ -f "$state/panes.txt" ]; then cat "$state/panes.txt"; fi ;;
  display-message) cat "$state/display.txt" ;;
  load-buffer) cat > "$state/buffer.txt" ;;
  capture-pane) cat "$state/capture.txt" ;;
  kill-window|kill-session) [ ! -e "$state/kill-fail" ] ;;
  *) echo "unknown tmux subcommand: $cmd" >&2; exit 2 ;;
esac
`;

